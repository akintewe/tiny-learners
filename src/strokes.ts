// Stroke paths for tracing, on a 100x100 grid (y grows downward).
// Each glyph is a list of strokes, in the order a child is taught to write them.

export type Pt = [number, number];

/** Points along an ellipse arc. Angles in degrees: 0 = right, 90 = down. */
function arc(cx: number, cy: number, rx: number, ry: number, from: number, to: number): Pt[] {
  const steps = Math.max(8, Math.ceil(Math.abs(to - from) / 10));
  return Array.from({ length: steps + 1 }, (_, i) => {
    const a = ((from + ((to - from) * i) / steps) * Math.PI) / 180;
    return [cx + rx * Math.cos(a), cy + ry * Math.sin(a)];
  });
}

